def apply_template(template, lang):
    if lang == "en":
        return template
    missing = [en for en, _ in TEMPLATE_ES if en not in template]
    if missing:
        raise ValueError("Spanish translation out of date; not found in template:\n  " + "\n  ".join(m[:90] for m in missing))
    for en, es in TEMPLATE_ES:
        template = template.replace(en, es)
    return template
